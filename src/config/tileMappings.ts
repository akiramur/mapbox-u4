/**
 * Atlas configuration and TerrainType → TileId mappings.
 * A new tile set only needs a layout + mapping (see TILESETS); nothing in
 * world/ or map/ changes.
 */

/**
 * One tile per terrain, or several variants. The variant index comes from the
 * pipeline (e.g. one floor type per building) and wraps around.
 */
export type TileMapping = Record<TerrainType, TileId | TileId[]>;

export function tileIdFor(mapping: TileMapping, terrain: TerrainType, variant = 0): TileId {
  const id = mapping[terrain];
  return Array.isArray(id) ? id[variant % id.length] : id;
}

/**
 * Terrains whose tile pattern scrolls down over time, like water in classic
 * 8-bit RPGs (the WebGL renderer shifts the tile's rows; tiles must wrap
 * vertically without a seam).
 */
export const SCROLLING_TERRAINS: ReadonlySet<TerrainType> = new Set([TerrainType.DeepWater, TerrainType.Water, TerrainType.ShallowWater]);

/** Letters for place names (A–Z → tile). An atlas without letters simply shows no names. */
export type GlyphMapping = Record<string, TileId>;


