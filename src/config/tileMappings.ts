/**
 * Flag rectangles [x, y, width, height] inside a tile, in atlas pixels
 * (layout.tileWidth × layout.tileHeight). The WebGL renderer makes the pixels
 * inside them flutter; the rest of the tile stays still.
 */
export type FlagRects = Partial<Record<TerrainType, [number, number, number, number]>>;

/**
 * How a creature moves: sail = deep and medium water; swim = any water; walk = open land; fly = land and water;
 * town = town ground at high zoom (floors, streets, grass, parks). Townsfolk ("town") only appear at high
 * zoom (LOCAL) and the others only below it.
 */
export type CreatureMove = "sail" | "swim" | "walk" | "fly" | "town";

export interface CreatureDef {
  /** Animation frames (tile ids), cycled. */
  frames: TileId[];
  moves: CreatureMove;
  /** Breathes fire (shoots the tile set's fireTile). */
  fire?: boolean;
}

/**
 * Wandering creatures for a tile set. `spawn` lists, per kind of terrain a
 * new creature appears on, which creatures can appear and their relative
 * weights: "deep" = deep and medium water, "shallow" = shallow water,
 * "land" = open land. "town" is used instead of all three at high zoom
 * (LOCAL), for townsfolk on town ground.
 */
export interface CreatureSet {
  defs: Record<string, CreatureDef>;
  spawn: { deep: [string, number][]; shallow: [string, number][]; land: [string, number][]; town?: [string, number][] };
  fireTile?: TileId;
}

/** A warp gate: frames = rising stages, then the open gate (last). */
export interface GateDef {
  frames: TileId[];
}

export interface TilesetConfig {
  id: string;
  name: string;
  url: string;
  layout: AtlasLayout;
  mapping: TileMapping;
  glyphs: GlyphMapping;
  flags?: FlagRects;
  creatures?: CreatureSet;
  gate?: GateDef;
}

